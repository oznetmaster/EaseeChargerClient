def flatten(s):
    if '$ref' in s:
        return flatten(SCHEMAS[s['$ref'].split('/')[-1]])
    if 'allOf' not in s: return s
    result = {'type':'object','properties':{},'required':[]}
    for part in s['allOf']:
        p=flatten(part)
        result['properties'].update(p.get('properties',{}))
        result['required'] += p.get('required',[])
        if isinstance(p.get('additionalProperties'),dict):result['additionalProperties']=p['additionalProperties']
    return result
