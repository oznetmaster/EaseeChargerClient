NAMES = {n: re.sub(r'[^a-zA-Z0-9_]', '_', n) for n in SCHEMAS}
KEYWORDS = {'from','to','event','params','object','string','operator','base','ref','out','in','lock','default','internal','namespace'}
def ident(n):
    n = re.sub(r'[^a-zA-Z0-9_]', '_', n)
    return '@'+n if n in KEYWORDS else n
def pascal(n):
    return ''.join(x[:1].upper()+x[1:] for x in re.split(r'[^a-zA-Z0-9]',n) if x)
def doc(s):
    return '/// <summary>'+html.escape(' '.join((s or 'Easee API model.').split()))+'</summary>\n'
def tag(name, text, attr=''):
    return '/// <'+name+attr+'>'+html.escape(' '.join(text.split()))+'</'+name+'>\n'
def write(p,s):
    p.write_bytes(s.replace('\r\n','\n').replace('\n','\r\n').encode('utf-8'))
