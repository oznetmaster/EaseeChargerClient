def typ(s, optional=False, allow_arbitrary=False):
    null = s.get('nullable',False) or optional
    if 'oneOf' in s:
        assert len(s['oneOf'])==1, 'Unresolved union: '+str(s)
        return typ(dict(s['oneOf'][0],nullable=null), allow_arbitrary=allow_arbitrary)
    if '$ref' in s: t=NAMES[s['$ref'].split('/')[-1]]
    elif s.get('type')=='array': t='List<'+typ(s['items'], allow_arbitrary=allow_arbitrary)+'>'
    elif s.get('type')=='object' and isinstance(s.get('additionalProperties'),dict):t='Dictionary<string, '+typ(s['additionalProperties'], allow_arbitrary=allow_arbitrary)+'>'
    elif s.get('type')=='string':
        t={'date-time':'DateTimeOffset','guid':'Guid','binary':'byte[]'}.get(s.get('format'),'string')
    elif s.get('type')=='integer':t='long' if s.get('format')=='int64' else 'int'
    elif s.get('type')=='number':t='decimal' if s.get('format')=='decimal' else 'double'
    elif s.get('type')=='boolean':t='bool'
    elif not s.get('type') or s.get('type')=='object':
        if not allow_arbitrary: raise ValueError('Unresearched open schema: '+str(s))
        t='EaseeValue'
    else:raise ValueError('Unknown schema '+str(s))
    return t+'?' if null else t

